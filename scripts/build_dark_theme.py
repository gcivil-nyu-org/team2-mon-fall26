"""Generate hotspots/static/hotspots/theme-dark.css from site.css.

The site's colours are mostly CSS variables, which the dark theme simply
redefines. Rules that still use a literal hex colour get a dark-theme override:
light backgrounds become dark tints of the same hue, borders become mid tones,
and dark text becomes light text. Everything is scoped to
``:root[data-theme="dark"]`` so the light theme is unchanged.

Run after changing colours in site.css:

    python3 scripts/build_dark_theme.py
"""

import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "hotspots/static/hotspots/site.css"
TARGET = ROOT / "hotspots/static/hotspots/theme-dark.css"
SCOPE = ':root[data-theme="dark"]'
HEX = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b(?![0-9a-fA-F])")

HEADER = f"""/* Dark theme for Connect NYC. GENERATED by scripts/build_dark_theme.py from
   site.css: edit the variables or the hand-written rules at the top of the script,
   not the generated overrides below. */
{SCOPE} {{
  color-scheme: dark;
  --brand: #7ab0ff;
  --brand-hover: #a3c8ff;
  --ink: #e4ecf7;
  --muted: #9fb1c7;
  --canvas: #0e1621;
  --line: #2a394c;
  --white: #162130;
}}
{SCOPE} .button-danger, {SCOPE} .nav-badge, {SCOPE} .hotspot-cluster span {{ color: #fff; }}
{SCOPE} .leaflet-tile-pane {{ filter: brightness(.72) contrast(1.08) saturate(.85); }}
{SCOPE} .leaflet-popup-content-wrapper, {SCOPE} .leaflet-popup-tip,
{SCOPE} .leaflet-bar a, {SCOPE} .leaflet-control-attribution {{ background: var(--white); color: var(--ink); }}
{SCOPE} .leaflet-control-attribution a {{ color: var(--brand); }}
{SCOPE} .leaflet-container {{ background: #1b2635; }}
{SCOPE} input, {SCOPE} select, {SCOPE} textarea {{ color: var(--ink); background-color: var(--white); }}
"""


def _rgb(hex_value):
    value = hex_value.lstrip("#")
    if len(value) == 3:
        value = "".join(char * 2 for char in value)
    return tuple(int(value[i : i + 2], 16) / 255 for i in (0, 2, 4))


def _hex(rgb):
    return "#" + "".join(f"{round(channel * 255):02x}" for channel in rgb)


def _luminance(rgb):
    return 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]


def _with_lightness(rgb, lightness, saturation_scale):
    hue, _, saturation = colorsys.rgb_to_hls(*rgb)
    return _hex(
        colorsys.hls_to_rgb(hue, lightness, min(1, saturation * saturation_scale))
    )


def dark_value(prop, hex_value):
    """The dark-theme colour for ``hex_value`` used in ``prop``, or None to keep it."""
    rgb = _rgb(hex_value)
    light = _luminance(rgb) > 0.55
    if prop.startswith("background"):
        return _with_lightness(rgb, 0.17, 0.45) if light else None
    if prop.startswith("border"):
        return _with_lightness(rgb, 0.33, 0.4) if light else None
    if prop == "color" or prop == "fill" or prop == "stroke":
        return None if light else _with_lightness(rgb, 0.78, 0.8)
    return None


def _convert_declarations(body):
    converted = []
    for declaration in body.split(";"):
        if ":" not in declaration:
            continue
        prop, value = declaration.split(":", 1)
        prop = prop.strip().lower()
        changed = False

        def replace(match):
            nonlocal changed
            mapped = dark_value(prop, match.group(0))
            if mapped is None:
                return match.group(0)
            changed = True
            return mapped

        new_value = HEX.sub(replace, value)
        if changed:
            converted.append(f"{prop}: {new_value.strip()}")
    return converted


def _scoped(selectors):
    return ", ".join(f"{SCOPE} {selector.strip()}" for selector in selectors.split(","))


def _rules(css):
    """Yield (selectors, body, at_rule) for each rule, one level of @media deep."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    index, depth, start, at_rule, prelude = 0, 0, 0, None, ""
    while index < len(css):
        char = css[index]
        if char == "{":
            text = css[start:index].strip()
            if depth == 0 and text.startswith("@"):
                at_rule, depth, start = text, 1, index + 1
            else:
                prelude, depth, start = text, depth + 1, index + 1
        elif char == "}":
            if (depth == 2 and at_rule) or (depth == 1 and not at_rule):
                yield prelude, css[start:index], at_rule
                depth -= 1
            else:
                depth, at_rule = 0, None
            start = index + 1
        index += 1


def build():
    css = SOURCE.read_text(encoding="utf-8")
    output = [HEADER]
    for selectors, body, at_rule in _rules(css):
        if (
            not selectors
            or selectors.startswith(":root")
            # Theme previews on the Settings page show both themes on purpose.
            or ".theme-" in selectors
            or (at_rule and not at_rule.startswith("@media"))
        ):
            continue
        declarations = _convert_declarations(body)
        if not declarations:
            continue
        rule = f"{_scoped(selectors)} {{ {'; '.join(declarations)}; }}"
        output.append(f"{at_rule} {{ {rule} }}" if at_rule else rule)
    TARGET.write_text("\n".join(output) + "\n", encoding="utf-8")
    return len(output) - 1


if __name__ == "__main__":
    print(f"Wrote {build()} dark-theme overrides to {TARGET.relative_to(ROOT)}")
